/**
 * Convert an ISO 3166-1 alpha-2 country code into the corresponding flag emoji
 * by mapping each letter to the regional indicator symbol code-point.
 */
export function flagFromISO2(iso2) {
  if (!iso2 || iso2.length !== 2) return '🏳️';
  const A = 0x1f1e6;
  const a = 'A'.charCodeAt(0);
  const cps = [...iso2.toUpperCase()].map((c) => A + (c.charCodeAt(0) - a));
  return String.fromCodePoint(...cps);
}
